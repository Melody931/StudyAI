/// Contiene todos los tamaños de espaciado utilizados
/// en la aplicación.
///
/// Centralizar estos valores ayuda a mantener un diseño
/// consistente y evita usar números "mágicos" repartidos
/// por todo el proyecto.
class AppSpacing {
  // Constructor privado para impedir instancias.
  AppSpacing._();

  /// Espaciado muy pequeño.
  static const double xs = 4.0;

  /// Espaciado pequeño.
  static const double sm = 8.0;

  /// Espaciado medio.
  static const double md = 16.0;

  /// Espaciado grande.
  static const double lg = 24.0;

  /// Espaciado extra grande.
  static const double xl = 32.0;

  /// Espaciado gigante.
  static const double xxl = 48.0;

  /// Espaciado máximo.
  static const double xxxl = 64.0;
}